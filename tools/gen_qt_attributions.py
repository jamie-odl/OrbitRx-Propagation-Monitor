"""Generate the Qt third-party attribution file shipped with OrbitRx (Risk P3).

Reads Qt's own ``qt_attribution.json`` metadata (the data behind "Licenses Used
in Qt") from source checkouts of the Qt modules whose libraries and plugins this
build ships -- qtbase (Qt6Core/Gui/Widgets/Network and the qtbase plugins),
qtsvg (Qt6Svg, qsvg, qsvgicon) and qtimageformats (qtiff, qwebp, qicns, qtga,
qwbmp) -- at the exact tag of the pinned PySide6_Essentials wheel (v6.12.0), and
writes one plain-text file with, for every third-party component Qt lists as
part of its libraries ("QtParts": "libs", the default), the name, version,
SPDX licence id, copyright lines and the full licence text(s).

Over-inclusive on purpose: components that Qt only compiles for other
platforms (Android, X11, Wayland, ...) are listed too, because the attribution
data does not say per Windows binary which ones are linked. Build-system, tool,
test and example-only entries are skipped.

Usage (offline, run once per Qt bump; the output is committed):

    python tools/gen_qt_attributions.py --tag v6.12.0 \\
        --module qtbase=PATH@SHA --module qtsvg=PATH@SHA \\
        --module qtimageformats=PATH@SHA \\
        --out third_party/qt/QT_THIRD_PARTY_ATTRIBUTIONS.txt
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SHIPPED_PARTS = {"libs"}


def _entries(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"), strict=False)
    return data if isinstance(data, list) else [data]


def _licence_files(entry: dict) -> list[str]:
    files = entry.get("LicenseFiles") or entry.get("LicenseFile") or []
    if isinstance(files, str):
        files = [files]
    return list(files)


def _copyright(entry: dict) -> str:
    value = entry.get("Copyright") or ""
    if isinstance(value, list):
        value = "\n".join(value)
    return value.strip()


def _spdx_fallback(qtbase: Path, licence_id: str) -> list[Path]:
    """When an entry names no licence file, use the SPDX text Qt ships."""
    out = []
    for token in licence_id.replace("(", " ").replace(")", " ").split():
        if token in {"AND", "OR", "WITH"}:
            continue
        candidate = qtbase / "LICENSES" / f"{token}.txt"
        if candidate.is_file() and candidate not in out:
            out.append(candidate)
    return out


def collect(modules: list[tuple[str, Path, str]]) -> list[dict]:
    qtbase = next(root for name, root, _ in modules if name == "qtbase")
    found = []
    for name, root, sha in modules:
        for attr in sorted(root.rglob("qt_attribution.json")):
            rel_dir = attr.parent.relative_to(root).as_posix()
            if "/tests/" in f"/{rel_dir}/" or "/examples/" in f"/{rel_dir}/":
                continue
            for entry in _entries(attr):
                parts = set(entry.get("QtParts") or ["libs"])
                if not parts & SHIPPED_PARTS:
                    continue
                licence_id = entry.get("LicenseId") or entry.get("License") or ""
                texts = []
                files = _licence_files(entry)
                paths = [attr.parent / f for f in files]
                if not paths or not all(p.is_file() for p in paths):
                    paths = [p for p in paths if p.is_file()] or _spdx_fallback(
                        qtbase, licence_id
                    )
                for p in paths:
                    texts.append((p.relative_to(root.parent).as_posix()
                                  if p.is_relative_to(root.parent) else p.name,
                                  p.read_text(encoding="utf-8", errors="replace")))
                found.append({
                    "module": name,
                    "sha": sha,
                    "dir": rel_dir,
                    "name": entry.get("Name") or entry.get("Id") or rel_dir,
                    "version": entry.get("Version") or "",
                    "licence_id": licence_id,
                    "licence": entry.get("License") or "",
                    "copyright": _copyright(entry),
                    "usage": (entry.get("QtUsage") or "").strip(),
                    "texts": texts,
                })
    found.sort(key=lambda e: (e["module"], e["name"].lower(), e["dir"]))
    return found


def render(tag: str, modules: list[tuple[str, Path, str]], entries: list[dict]) -> str:
    rule = "=" * 78
    lines = [
        "OrbitRx Propagation Monitor: third-party components bundled in Qt",
        "",
        f"Generated by tools/gen_qt_attributions.py from Qt's qt_attribution.json",
        f"metadata (the data behind \"Licenses Used in Qt\") at Qt {tag}:",
    ]
    for name, _, sha in modules:
        lines.append(f"  {name} {tag} (commit {sha})")
    lines += [
        "",
        "These components are compiled into the Qt libraries and plugins this",
        "build ships (Qt6Core, Qt6Gui, Qt6Widgets, Qt6Network, Qt6Svg and the",
        "qtbase, qtsvg and qtimageformats plugins under _internal/PySide6). The",
        "list is deliberately over-inclusive: components Qt only builds for other",
        "platforms are included because Qt's data does not say per Windows binary",
        "which ones are linked. Qt itself is covered by NOTICE and",
        "third_party/qt/LICENSES/.",
        "",
        f"{len(entries)} components.",
        "",
    ]
    for e in entries:
        lines += [rule, f"{e['name']}" + (f" {e['version']}" if e["version"] else ""),
                  f"Qt module: {e['module']} ({e['dir']})",
                  f"Licence: {e['licence_id'] or e['licence']}"]
        if e["usage"]:
            lines.append(f"Used in Qt: {e['usage']}")
        if e["copyright"]:
            lines += ["Copyright:", *("  " + c for c in e["copyright"].splitlines())]
        for label, text in e["texts"]:
            lines += ["", f"--- {label} ---", text.rstrip("\n")]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tag", required=True)
    parser.add_argument("--module", action="append", required=True,
                        help="NAME=PATH@COMMIT")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    modules = []
    for spec in args.module:
        name, rest = spec.split("=", 1)
        path, sha = rest.rsplit("@", 1)
        modules.append((name, Path(path).resolve(), sha))
    entries = collect(modules)
    args.out.write_text(render(args.tag, modules, entries), encoding="utf-8", newline="\n")
    print(f"wrote {len(entries)} components to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
